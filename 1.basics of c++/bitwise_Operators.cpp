// OPERATOR PRECEDENCE
//  Parentheses (): Always calculated first. Put things inside brackets to change the normal order.
//  Multiplication, Division, and Modulus *, /, %: Calculated next, going from left to right.
//  Addition and Subtraction +, -: Calculated after multiplication and division, going from left to right.
//  Comparison <, >, ==: Used to check if values are equal or if one is larger.
//  Logical Operators &&, ||: Used to check "and" or "or" conditions.
//  Assignment =: Saves the final answer into a variable last.
#include<iostream>
using namespace std;
int main(){
    cout<<sizeof(int)<<endl;
    cout<<sizeof(long int)<<endl;
    cout<<sizeof(short int)<<endl;
    cout<<sizeof(long long int)<<endl;
}